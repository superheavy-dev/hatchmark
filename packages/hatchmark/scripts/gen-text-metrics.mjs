// Generates src/render/text-metrics.ts from the bundled IBM Plex Sans files in assets/fonts:
// advance widths for every code point the subsets cover, and the kerning (GPOS kern plus the fi/fl
// ligatures) between every pair of printable ASCII characters, in font units. Kerning between
// accented letters is rare in labels and would multiply the table size. The renderer measures text with this
// table, so layout needs no canvas, DOM or font file at run time. Run: pnpm gen:text-metrics
import { readdirSync, writeFileSync } from "node:fs";
import * as fontkit from "fontkit";

const FONTS = new URL("../assets/fonts/", import.meta.url);
const OUT = new URL("../src/render/text-metrics.ts", import.meta.url);
const WEIGHTS = { 400: "Regular", 500: "Medium", 600: "SemiBold" };

const lines = [
  "// Generated by scripts/gen-text-metrics.mjs from assets/fonts (IBM Plex Sans, SIL OFL 1.1).",
  "// Do not edit; run pnpm gen:text-metrics after changing the bundled fonts.",
  "",
  "/** Advance widths and kerning of the bundled IBM Plex Sans subsets, in font units. */",
  "export interface FontMetrics {",
  "  /** Code points and advance widths, alternating: [codePoint, width, codePoint, width, ...]. */",
  "  advances: number[];",
  "  /** Kerning entries separated by tabs: two ASCII characters, then the adjustment in font units. */",
  "  kerning: string;",
  "}",
  "",
];
let unitsPerEm;
const entries = [];
for (const [weight, style] of Object.entries(WEIGHTS)) {
  const files = readdirSync(FONTS)
    .filter((f) => f.startsWith(`IBMPlexSans-${style}-`) && f.endsWith(".woff2"))
    .sort();
  const fonts = files.map((f) => fontkit.openSync(new URL(f, FONTS).pathname));
  unitsPerEm ??= fonts[0].unitsPerEm;
  const owner = new Map();
  for (const font of fonts) {
    for (const cp of font.characterSet) {
      if (cp < 32 || owner.has(cp)) continue;
      if (font.glyphForCodePoint(cp).id === 0) continue;
      owner.set(cp, font);
    }
  }
  const cps = [...owner.keys()].sort((a, b) => a - b);
  const advance = (cp) => owner.get(cp).glyphForCodePoint(cp).advanceWidth;
  const advances = cps.flatMap((cp) => [cp, advance(cp)]);
  const kerning = [];
  const ascii = cps.filter((cp) => cp <= 126);
  for (const a of ascii) {
    for (const b of ascii) {
      const text = String.fromCodePoint(a, b);
      const laid = owner
        .get(a)
        .layout(text)
        .positions.reduce((sum, p) => sum + p.xAdvance, 0);
      const delta = Math.round(laid - advance(a) - advance(b));
      if (delta !== 0) kerning.push(`${text}${delta}`);
    }
  }
  entries.push(
    `  ${weight}: {\n    advances: [${advances.join(", ")}],\n    kerning: ${JSON.stringify(kerning.join("\t"))},\n  },`,
  );
  console.log(`weight ${weight}: ${cps.length} code points, ${kerning.length} kerning pairs`);
}
lines.push(`export const UNITS_PER_EM = ${unitsPerEm};`, "");
lines.push(
  "export const FONT_METRICS: Record<400 | 500 | 600, FontMetrics> = {",
  ...entries,
  "};",
  "",
);
writeFileSync(OUT, lines.join("\n"));
